#!/usr/bin/env python3
"""Generate exact DVN miner subsidy lookup from approved consensus formula.

Emits a Rust no_std const slice, to be integrated into FRAME mining rewards
ONLY alongside authenticated issuance storage and fee separation.
"""
import argparse
from pathlib import Path

INITIAL = 500_000_000
NUMERATOR = 399
DENOMINATOR = 400
EPOCH_BLOCKS = 50_000
MINING_CAP = 9_000_000_000_000_000

def exact_rewards():
    numerator = INITIAL
    denominator = 1
    epoch = 0
    while True:
        reward = numerator // denominator
        if reward < 1:
            break
        yield reward
        epoch += 1
        numerator *= NUMERATOR
        denominator *= DENOMINATOR

def generate() -> str:
    values = list(exact_rewards())
    assert values[0] == INITIAL
    assert values[1] == 498_750_000
    assert values[2] == 497_503_125
    assert values[-1] >= 1
    assert INITIAL * pow(NUMERATOR, len(values)) < pow(DENOMINATOR, len(values))
    rows = ["    " + ", ".join(f"{n}u64" for n in values[i:i+10]) + ","
            for i in range(0, len(values), 10)]
    return (
        "// Generated by scripts/generate_emission_table.py; DO NOT EDIT.\n"
        "// floor(500000000 * (399/400)^epoch), then 1-base-unit tail.\n"
        f"// {len(values)} exact rational reward epochs; 50000 blocks per epoch.\n"
        "pub const DVN_INITIAL_SUBSIDY: u64 = 500_000_000;\n"
        "pub const DVN_EPOCH_BLOCKS: u32 = 50_000;\n"
        "pub const DVN_MINING_CAP: u128 = 9_000_000_000_000_000;\n"
        "pub const DVN_REWARDS: &[u64] = &[\n"
        + "\n".join(rows) + "\n];\n"
        "pub fn dvn_epoch_reward(epoch: u32) -> u64 {\n"
        "    DVN_REWARDS.get(epoch as usize).copied().unwrap_or(1)\n"
        "}\n"
    )

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate())
    print(f"Generated {args.output} (lookup table; no FRAME integration implied)")

if __name__ == "__main__":
    main()
